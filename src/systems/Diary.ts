/**
 * Diary entries for days 1..(up to current day). A new entry is added every
 * 3 days (day 3, 6, 9, …). Texts cycle deterministically through DIARY_TEXTS.
 */
export function getDiaryEntries(currentDay: number): DiaryEntry[] {
  const entries: DiaryEntry[] = [];
  for (let d = 3; d <= currentDay; d += 3) {
    const idx = ((d / 3) - 1) % DIARY_TEXTS.length;
    entries.push({ day: d, text: DIARY_TEXTS[idx] });
  }
  return entries;
}
